/**
 * Writes the demo dataset as SQL for a Supabase project (so the real backend can be tried with data).
 *   npm run seed:sql          → supabase/seed.sql   (run it in the SQL editor after 001_schema.sql)
 * Demo ids are mapped to deterministic UUIDs. Profiles are created without auth users;
 * set an e-mail on a profile to be able to log in as that person.
 */
import { createHash } from 'node:crypto';
import { generateDemoData } from '../src/lib/demo';

const { data } = generateDemoData({ seed: 42 });
const uuid = (id: string) => {
  const h = createHash('sha1').update('beauty-demo:' + id).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (Array.isArray(v) && v.some((x) => x === null || typeof x === 'object')) return `'${JSON.stringify(v)}'::jsonb`;
  if (Array.isArray(v)) return `'{${v.join(',')}}'`;
  if (typeof v === 'object') return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const out: string[] = ['-- generated by scripts/generate-seed-sql.ts', 'begin;'];
const insert = (table: string, cols: string[], rows: unknown[][]) => {
  for (let i = 0; i < rows.length; i += 500) {
    out.push(`insert into ${table} (${cols.join(',')}) values`);
    out.push(rows.slice(i, i + 500).map((r) => `(${r.map(q).join(',')})`).join(',\n') + ';');
  }
};
insert('regions', ['id', 'name'], data.regions.map((r) => [uuid(r.id), r.name]));
insert('stores', ['id', 'name', 'region_id', 'hours', 'lat', 'lng', 'headcount'], data.stores.map((s) => [uuid(s.id), s.name, uuid(s.regionId), s.hours, s.lat, s.lng, s.headcount]));
insert(
  'profiles',
  ['id', 'name', 'role', 'store_id', 'region_id', 'is_brand_promoter', 'brand', 'availability', 'shifts_per_week', 'home_lat', 'home_lng', 'active'],
  data.sellers.map((s) => [uuid(s.id), s.name, s.role, s.storeId && uuid(s.storeId), s.regionId && uuid(s.regionId), s.isBrandPromoter, s.brand, s.availability, s.shiftsPerWeek, s.homeLat, s.homeLng, s.active]),
);
insert('shifts', ['id', 'seller_id', 'store_id', 'date', 'start_hour', 'end_hour', 'target', 'closed'], data.shifts.map((s) => [uuid(s.id), uuid(s.sellerId), uuid(s.storeId), s.date, s.startHour, s.endHour, s.target, s.closed]));
insert(
  'sales',
  ['id', 'seller_id', 'co_seller_id', 'store_id', 'shift_id', 'ts', 'amount', 'units', 'categories', 'upsell', 'club_signup', 'is_return'],
  data.sales.map((s) => [uuid(s.id), uuid(s.sellerId), s.coSellerId && uuid(s.coSellerId), uuid(s.storeId), s.shiftId && uuid(s.shiftId), s.ts, s.amount, s.units, s.categories, s.upsell, s.clubSignup, s.isReturn]),
);
insert('interactions', ['id', 'seller_id', 'store_id', 'ts'], data.interactions.map((i) => [uuid(i.id), uuid(i.sellerId), uuid(i.storeId), i.ts]));
insert('daily_targets', ['store_id', 'date', 'target'], data.targets.map((t) => [uuid(t.storeId), t.date, t.target]));
out.push('commit;');
process.stdout.write(out.join('\n') + '\n');
